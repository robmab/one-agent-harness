"""Generates the OpenCode and Copilot copies of the agents from Claude's originals.

Claude reads the original (`personal\\agents\\*.agent.md`) as is, with `tools: Read, Grep, ...`.
Each tool names its tools its own way, so there are two copies:
- OpenCode 2 ignores a whole agent if its frontmatter has `tools:` → a copy without that line
  (OpenCode-specific settings, such as steps and denied edits, live in `opencode.jsonc`).
- VS Code doesn't know Claude's names and leaves the agent with no tools → a copy with its aliases.

Run it after touching `personal\\agents\\*.agent.md`:  py -3 sync.py
With --check it writes nothing: exits with 1 if any copy is out of date.
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, '..', 'personal', 'agents')
# Optional: the agents' model in Copilot, as the model picker names it ('<model>' or ['<model>', '<fallback>']).
# None = the chat's model. Claude's `model:` (sonnet, opus…) is never copied: the other tools don't know those names.
COPILOT_MODEL = None
# (target folder, extension, `tools:` line that replaces the original (None = remove it), model (None = none))
TARGETS = [
    (os.path.join(HERE, 'agents'), '.md', None, None),
    (os.path.join(HERE, '..', 'copilot', 'agents'), '.agent.md', 'tools: [read, search, execute]', COPILOT_MODEL),
]


def generated(text, source_name, tools, model=None):
    header, body = text.split('\n---', 1)
    header = re.sub(r'(?m)^model:.*\n?', '', header)
    header = re.sub(r'(?m)^tools:.*\n?', '' if tools is None else tools + '\n', header).rstrip('\n')
    if model:
        header += '\nmodel: ' + json.dumps(model, ensure_ascii=False)
    note = '<!-- Generated by opencode/sync.py from personal/agents/%s: don\'t edit it here -->\n' % source_name
    return header + '\n---' + body.replace('\n', '\n' + note, 1)


def pairs():
    """(source file, generated file, expected text) for each agent and target."""
    for source_name in sorted(n for n in os.listdir(SOURCE) if n.endswith('.agent.md')):
        with io.open(os.path.join(SOURCE, source_name), encoding='utf-8-sig') as f:
            text = f.read().replace('\r\n', '\n')
        for folder, ext, tools, model in TARGETS:
            target = os.path.join(folder, source_name.replace('.agent.md', ext))
            yield source_name, target, generated(text, source_name, tools, model)


def current(path):
    if not os.path.isfile(path):
        return None
    with io.open(path, encoding='utf-8') as f:
        return f.read().replace('\r\n', '\n')


def name(path):
    return os.path.relpath(path, os.path.join(HERE, '..')).replace('\\', '/')


def overwritten_sources():
    """Originals with VS Code's `tools:` (`[read, ...]`): Claude leaves them with no tools.

    It happens when Copilot edits the original and later restores its copy (VS Code's "editing sessions").
    """
    bad = []
    for source_name in sorted(n for n in os.listdir(SOURCE) if n.endswith('.agent.md')):
        with io.open(os.path.join(SOURCE, source_name), encoding='utf-8-sig') as f:
            if re.search(r'(?m)^tools:\s*\[', f.read().split('\n---', 1)[0]):
                bad.append(source_name)
    return bad


def main():
    overwritten = overwritten_sources()
    if overwritten:
        print("The original has VS Code's tools: and Claude gets no tools: "
              + ', '.join(overwritten) + '. Set it back to "tools: Read, Grep, Glob, Bash".')
        return 1
    if '--check' in sys.argv:
        stale = [name(d) for _, d, expected in pairs() if current(d) != expected]
        print('Out of date: ' + ', '.join(stale) if stale else 'Up to date.')
        return 1 if stale else 0
    done = []
    for _, target, expected in pairs():
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with io.open(target, 'w', encoding='utf-8', newline='') as f:
            f.write(expected)
        done.append(name(target))
    print('Generated: ' + ', '.join(done))
    return 0


if __name__ == '__main__':
    sys.exit(main())
